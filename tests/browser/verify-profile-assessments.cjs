// Run against the isolated assessment QA server, never production.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'C:/Users/lemue/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict'), fs = require('node:fs');
const origin = process.env.ASSESSMENT_QA_ORIGIN || 'http://127.0.0.1:9560';
assert.ok(/^http:\/\/127\.0\.0\.1:\d+$/.test(origin));
const output = 'work/assessment/profile-results';
const positions = JSON.parse(fs.readFileSync('lib/assessment/skillsPositions.json', 'utf8'));
const studentId = '30000000-0000-4000-8000-000000000001';
const visible = l => l.waitFor({ state: 'visible', timeout: 30000 });
(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } }), page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await context.request.get(origin + '/__qa/login');
    let latest;
    for (let i = 0; i < 12; i++) {
      const start = await (await context.request.post(origin + '/api/student/assessment', { data: { action: 'start' } })).json();
      assert.ok(start.attempt?.id, JSON.stringify(start));
      const answers = Object.fromEntries(positions.slice(0, 24).map(q => [q.id, q.acceptedMoves[0]]));
      latest = await (await context.request.post(origin + '/api/student/assessment', { data: { action: 'submit', attemptId: start.attempt.id, answers } })).json();
      assert.equal(latest.attempt.correct_count, 24);
    }
    const active = await (await context.request.post(origin + '/api/student/assessment', { data: { action: 'start' } })).json();
    const history = await (await context.request.get(origin + '/api/student/assessment/history')).json();
    assert.equal(history.results.length, 10); assert.equal(history.hasMore, true);
    assert.equal(history.results[0].id, latest.attempt.id); assert.ok(!('answers' in history.results[0]));
    assert.ok(!history.results.some(r => r.id === active.attempt.id));
    await page.goto(origin + '/student#test-results');
    const results = page.getByRole('region', { name: 'Test results', exact: true });
    await visible(results.getByRole('link', { name: 'Open analysis review' }).first());
    assert.equal(await results.getByText('80/100', { exact: true }).count(), 10);
    await results.evaluate(e => window.scrollTo(0, e.getBoundingClientRect().top + window.scrollY - 80)); await page.screenshot({ path: output + '/student-desktop.png' });
    await results.getByRole('button', { name: 'Older results' }).click();
    await visible(results.getByText('Page 2', { exact: true }));
    await visible(results.getByRole('link', { name: 'Open analysis review' }).first());
    assert.equal(await results.getByRole('link', { name: 'Open analysis review' }).count(), 2);
    await results.getByRole('button', { name: 'Newer results' }).click();
    await visible(results.getByText('Page 1', { exact: true }));
    await visible(results.getByRole('link', { name: 'Open analysis review' }).first());
    await page.setViewportSize({ width: 390, height: 844 }); await results.evaluate(e => window.scrollTo(0, e.getBoundingClientRect().top + window.scrollY - 80));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: output + '/student-mobile.png' });
    await results.getByRole('link', { name: 'Open analysis review' }).first().click();
    await visible(page.getByRole('region', { name: 'Test analysis review' }));
    await page.getByRole('button', { name: 'Solution line', exact: true }).click();
    assert.equal(await page.locator('[data-chess-board]').count(), 1);
    await page.screenshot({ path: output + '/student-review.png', fullPage: true });
    const unchanged = await (await context.request.get(origin + '/api/student/assessment?attempt=' + latest.attempt.id)).json();
    const normalized = attempt => ({ ...attempt, ...Object.fromEntries(['started_at', 'deadline_at', 'completed_at'].map(key => [key, new Date(attempt[key]).toISOString()])) });
    assert.deepEqual(normalized(unchanged.attempt), normalized(latest.attempt));
    await page.goto(origin + '/student/training/assessment/' + active.attempt.id);
    await visible(page.getByText('This page could not be found.', { exact: true }));
    assert.equal(await page.getByRole('region', { name: 'Test analysis review' }).count(), 0);
    const teacher = await browser.newContext({ viewport: { width: 1440, height: 1000 } }), t = await teacher.newPage();
    await teacher.request.get(origin + '/__qa/teacher');
    await t.goto(origin + '/admin/students?student=' + studentId);
    const teacherResults = t.getByRole('region', { name: 'Test results', exact: true });
    await visible(teacherResults.getByRole('link', { name: 'Open analysis review' }).first());
    assert.ok((await teacherResults.getByRole('link', { name: 'Open analysis review' }).first().getAttribute('href')).startsWith('/admin/assessments/'));
    await teacherResults.evaluate(e => window.scrollTo(0, e.getBoundingClientRect().top + window.scrollY - 80)); await t.screenshot({ path: output + '/teacher-desktop.png' });
    await teacherResults.getByRole('link', { name: 'Open analysis review' }).first().click();
    await visible(t.getByRole('region', { name: 'Test analysis review' }));
    const peer = await browser.newContext(), p = await peer.newPage(); await peer.request.get(origin + '/__qa/login?user=1');
    assert.equal((await peer.request.get(origin + '/api/student/assessment/history?studentId=' + studentId)).status(), 403);
    await p.goto(origin + '/student/training/assessment/' + latest.attempt.id);
    await visible(p.getByText('This page could not be found.', { exact: true }));
    assert.equal(await p.getByRole('region', { name: 'Test analysis review' }).count(), 0);
    await p.goto(origin + '/student/students/battle_a');
    assert.equal(await p.getByRole('region', { name: 'Test results', exact: true }).count(), 0);
    await p.goto(origin + '/student#test-results'); await visible(p.getByText('No completed tests yet.', { exact: true }));
    const anonymous = await browser.newContext(), a = await anonymous.newPage();
    assert.equal((await anonymous.request.get(origin + '/api/student/assessment/history?studentId=' + studentId)).status(), 401);
    await a.goto(origin + '/app/students/battle_a');
    assert.equal(await a.getByRole('region', { name: 'Test results', exact: true }).count(), 0);
    let fail = true;
    await page.route('**/api/student/assessment/history?**', async route => fail ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Temporary test failure' }) }) : route.continue());
    await page.goto(origin + '/student#test-results'); await visible(results.getByRole('alert'));
    fail = false; await results.getByRole('button', { name: 'Retry', exact: true }).click(); await visible(results.getByRole('link', { name: 'Open analysis review' }).first());
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, checks: ['profile score/date/version', 'newest first and pagination', 'active test excluded', 'student review', 'teacher profile review', 'immutable answers', 'peer/public privacy', 'error/retry', 'mobile layout'], screenshots: output }));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
